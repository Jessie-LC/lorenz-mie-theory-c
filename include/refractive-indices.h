double N2_Peck0C(double wavelength) {
    // 1+6.8552E-5+3.243157E-2/(144-pow(x,-2))
    return 1.0 + 6.8552e-5 + 3.243157e-2 / (144.0 - pow(wavelength, -2.0));
}

