int BinarySearch(int lowIndex, int highIndex, int size, double toFind, const double arr[]) {
	while (lowIndex < highIndex) {
		int midIndex = (lowIndex + highIndex) >> 1;
		if (arr[midIndex] < toFind) {
			lowIndex = midIndex + 1;
		}
		else if (arr[midIndex] > toFind) {
			highIndex = midIndex;
		}
		else {
			return midIndex;
		}
	}
	return -1;
}

fcomplex64_t Water_Complex(double wavelength) {
    double lambdaMin = wavelength - 0.5, lambdaMax = wavelength - 0.5;
    double     start = fmax(lambdaMin, Water_Wavelengths[0]);
    double       end = fmin(lambdaMax, Water_Wavelengths[168]);

    int idx = (abs(0 - BinarySearch(0, 168, 169, start, Water_Wavelengths))) - 1;

    if (end <= start) {
        fcomplex64_t nill = { 0.0, 0.0 };
        return nill;
    }

    double waterR = 0.0;
    {
        double result = 0.0;
        for(int i = idx; i < 168 && end >= Water_Wavelengths[i]; ++i) {
            double     a = Water_Wavelengths[i];
            double     b = Water_Wavelengths[i + 1];
            double    ca = fmax(a, start);
            double    cb = fmin(b, end);
            double    fa = Water_Real[i];
            double    fb = Water_Real[i + 1];
            double invAB = 1.0 / (b - a);

            if (ca >= cb) {
                continue;
            }

            double interpA = fa * (1.0 - ((ca - a) * invAB)) + fb * ((ca - a) * invAB);
            double interpB = fa * (1.0 - ((cb - a) * invAB)) + fb * ((cb - a) * invAB);

            result += 0.5 * (interpA + interpB) * (cb - ca);
        }
        waterR = result / (lambdaMax - lambdaMin);
    }
    double waterI = 0.0;
    {
        double result = 0.0;
        for(int i = idx; i < 168 && end >= Water_Wavelengths[i]; ++i) {
            double     a = Water_Wavelengths[i];
            double     b = Water_Wavelengths[i + 1];
            double    ca = fmax(a, start);
            double    cb = fmin(b, end);
            double    fa = Water_Imag[i];
            double    fb = Water_Imag[i + 1];
            double invAB = 1.0 / (b - a);

            if (ca >= cb) {
                continue;
            }

            double interpA = fa * (1.0 - ((ca - a) * invAB)) + fb * ((ca - a) * invAB);
            double interpB = fa * (1.0 - ((cb - a) * invAB)) + fb * ((cb - a) * invAB);

            result += 0.5 * (interpA + interpB) * (cb - ca);
        }
        waterI = result / (lambdaMax - lambdaMin);
    }

    fcomplex64_t water = { waterR, waterI };
    return water;
}

